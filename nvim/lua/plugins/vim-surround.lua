    -- │ Change surroundings:                                        │
    -- │   cs{old}{new}       Change existing surrounding            │
    -- │   cS{old}{new}       Change + put on separate lines         │
    -- │                                                             │
    -- │ Delete surroundings:                                        │
    -- │   ds{char}           Delete existing surrounding            │
    -- │                                                             │
    -- │ Visual mode:                                                │
    -- │   S{char}            Surround visual selection              │
    -- │   gS{char}           Surround selection on separate lines   │
